create extension if not exists pgcrypto;

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  plan text not null default 'basic' check (plan in ('basic', 'professional')),
  status text not null default 'active' check (status in ('active', 'suspended', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table if not exists public.clientes (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations(id) on delete cascade,
  nome text not null,
  cnpj text,
  tel text,
  email text,
  endereco text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.catalogo (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations(id) on delete cascade,
  nome text not null,
  valor numeric(14,2) not null default 0 check (valor >= 0),
  categoria text not null default 'Outros',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.config (
  id bigint generated by default as identity primary key,
  organization_id uuid references public.organizations(id) on delete cascade,
  nome text not null default '',
  cnpj text,
  tel text,
  email text,
  endereco text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orcamentos (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations(id) on delete cascade,
  numero bigint generated by default as identity,
  cliente_nome text,
  cnpj_cli text,
  referencia text,
  valido_ate date,
  desconto_tipo text default 'pct' check (desconto_tipo in ('pct', 'val')),
  desconto_valor numeric(14,2) not null default 0 check (desconto_valor >= 0),
  itens jsonb not null default '[]'::jsonb,
  observacoes text,
  empresa text,
  cnpj_emp text,
  tel_emp text,
  email_emp text,
  solicitante text,
  total numeric(14,2) not null default 0 check (total >= 0),
  status text not null default 'pendente' check (status in ('pendente', 'aprovado', 'recusado', 'cancelado')),
  public_token uuid not null default gen_random_uuid(),
  public_enabled boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

